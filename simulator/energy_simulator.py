# ==========================================================
# THREAD-SAFE CONTROL STATE
# ==========================================================

class ControlState:
    """
    Stores the latest AI control command.

    MQTT receives commands in a background thread while the simulator
    generates telemetry in the main loop, so a lock is used.
    """

    def __init__(self) -> None:

        self._lock = Lock()

        self._latest_command: Optional[
            ControlCommand
        ] = None

    def update(
        self,
        command: ControlCommand,
    ) -> None:

        with self._lock:

            self._latest_command = command

    def consume_latest(
        self,
    ) -> Optional[ControlCommand]:
        """
        Return the latest command once.

        After consumption it is cleared so a stale command is not
        applied repeatedly forever if the controller stops.
        """

        with self._lock:

            command = self._latest_command

            self._latest_command = None

            return command


