# ==========================================================
# ENERGY SIMULATOR
# ==========================================================

class SmartEnergySimulator:
    """
    Simulates the energy environment of a smart commercial building.

    Important:
        Values are correlated instead of independently random.

    Example:

        Higher occupancy
            ↓
        Higher equipment usage
            ↓
        Higher building demand

    Higher cloud cover
            ↓
        Lower solar generation
    """

    def __init__(
        self,
    ) -> None:

        self.reading_id = 0

        # --------------------------------------------------
        # Initial battery state
        # --------------------------------------------------

        self.battery_soc = 72.0

        # --------------------------------------------------
        # Smooth environmental states
        # --------------------------------------------------

        self.cloud_cover = random.uniform(
            10,
            30,
        )

        self.humidity = random.uniform(
            45,
            60,
        )

        # --------------------------------------------------
        # Last applied control information
        # --------------------------------------------------

        self.last_control_action = (
            "NO_CONTROL_RECEIVED"
        )

        self.last_control_mode = "HOLD"

        self.last_battery_power_kw = 0.0

        self.last_load_reduction_kw = 0.0

    # ======================================================
    # UTILITY
    # ======================================================

    @staticmethod
    def clamp(
        value: float,
        minimum: float,
        maximum: float,
    ) -> float:

        return max(
            minimum,
            min(
                value,
                maximum,
            ),
        )

    # ======================================================
    # OCCUPANCY MODEL
    # ======================================================

    def generate_occupancy(
        self,
        hour: float,
    ) -> float:

        if hour < 6:

            occupancy = random.uniform(
                2,
                5,
            )

        elif hour < 8:

            occupancy = random.uniform(
                5,
                20,
            )

        elif hour < 10:

            occupancy = random.uniform(
                45,
                75,
            )

        elif hour < 17:

            occupancy = random.uniform(
                75,
                95,
            )

        elif hour < 20:

            occupancy = random.uniform(
                30,
                65,
            )

        else:

            occupancy = random.uniform(
                5,
                20,
            )

        return round(
            self.clamp(
                occupancy,
                0,
                100,
            ),
            2,
        )

    # ======================================================
    # WEATHER MODEL
    # ======================================================

    def update_cloud_cover(
        self,
    ) -> float:

        movement = random.uniform(
            -3,
            3,
        )

        self.cloud_cover += movement

        self.cloud_cover = self.clamp(
            self.cloud_cover,
            0,
            100,
        )

        return round(
            self.cloud_cover,
            2,
        )

    def generate_temperature(
        self,
        hour: float,
    ) -> float:

        daily_cycle = math.sin(
            (
                hour - 8
            )
            / 24
            * 2
            * math.pi
        )

        base_temperature = 28

        temperature = (
            base_temperature
            + 6 * daily_cycle
            + random.uniform(
                -0.5,
                0.5,
            )
        )

        return round(
            temperature,
            2,
        )

    def update_humidity(
        self,
        temperature: float,
    ) -> float:

        target_humidity = (
            68
            - (
                temperature
                - 22
            )
            * 1.5
        )

        self.humidity += (
            target_humidity
            - self.humidity
        ) * 0.1

        self.humidity += random.uniform(
            -1,
            1,
        )

        self.humidity = self.clamp(
            self.humidity,
            25,
            90,
        )

        return round(
            self.humidity,
            2,
        )

    # ======================================================
    # SOLAR GENERATION
    # ======================================================

    def generate_solar_power(
        self,
        hour: float,
        cloud_cover: float,
    ) -> float:

        sunrise = 6

        sunset = 18

        if (
            hour < sunrise
            or hour > sunset
        ):

            return 0.0

        daylight_progress = (
            hour - sunrise
        ) / (
            sunset - sunrise
        )

        solar_curve = math.sin(
            math.pi
            * daylight_progress
        )

        cloud_efficiency = (
            1
            - 0.65
            * cloud_cover
            / 100
        )

        solar_power = (
            MAX_SOLAR_CAPACITY_KW
            * solar_curve
            * cloud_efficiency
        )

        solar_power += random.uniform(
            -1.5,
            1.5,
        )

        return round(
            max(
                0,
                solar_power,
            ),
            2,
        )

    # ======================================================
    # BUILDING DEMAND
    # ======================================================

    def generate_building_demand(
        self,
        temperature: float,
        occupancy: float,
    ) -> float:

        # Servers, lighting, security, base electronics.
        base_load = 25

        occupancy_load = (
            occupancy
            * 0.45
        )

        cooling_requirement = max(
            temperature - 24,
            0,
        )

        hvac_load = (
            cooling_requirement
            * 3.2
        )

        operational_variation = (
            random.uniform(
                -3,
                3,
            )
        )

        total_demand = (
            base_load
            + occupancy_load
            + hvac_load
            + operational_variation
        )

        return round(
            max(
                total_demand,
                10,
            ),
            2,
        )

    # ======================================================
    # ELECTRICITY PRICE
    # ======================================================

    def generate_grid_price(
        self,
        hour: float,
        demand_kw: float,
    ) -> float:

        if 0 <= hour < 6:

            base_price = 4.8

        elif hour < 9:

            base_price = 6.5

        elif hour < 17:

            base_price = 8.0

        elif hour < 22:

            base_price = 11.0

        else:

            base_price = 5.5

        demand_component = max(
            demand_kw - 70,
            0,
        ) * 0.025

        price = (
            base_price
            + demand_component
            + random.uniform(
                -0.25,
                0.25,
            )
        )

        return round(
            max(
                price,
                3,
            ),
            2,
        )

    # ======================================================
    # GRID CARBON INTENSITY
    # ======================================================

    def generate_grid_carbon_intensity(
        self,
        hour: float,
    ) -> float:

        if 18 <= hour <= 22:

            base = 610

        elif 10 <= hour <= 16:

            base = 450

        else:

            base = 520

        carbon = (
            base
            + random.uniform(
                -25,
                25,
            )
        )

        return round(
            carbon,
            2,
        )

    # ======================================================
    # BATTERY PHYSICS
    # ======================================================

    def calculate_max_available_discharge_kw(
        self,
    ) -> float:
        """
        Calculates the maximum physically available discharge power
        for the current 2-second simulation interval.

        This prevents SOC from dropping below MIN_BATTERY_SOC.
        """

        available_energy_kwh = (
            (
                self.battery_soc
                - MIN_BATTERY_SOC
            )
            / 100
            * BATTERY_CAPACITY_KWH
        )

        available_energy_kwh = max(
            available_energy_kwh,
            0,
        )

        interval_hours = (
            UPDATE_INTERVAL_SECONDS
            / 3600
        )

        if interval_hours <= 0:

            return 0.0

        maximum_power_from_energy = (
            available_energy_kwh
            * BATTERY_DISCHARGE_EFFICIENCY
            / interval_hours
        )

        return max(
            0.0,
            min(
                MAX_BATTERY_DISCHARGE_KW,
                maximum_power_from_energy,
            ),
        )

    def calculate_max_available_charge_kw(
        self,
    ) -> float:
        """
        Calculates charging headroom without crossing
        MAX_BATTERY_SOC.
        """

        available_capacity_kwh = (
            (
                MAX_BATTERY_SOC
                - self.battery_soc
            )
            / 100
            * BATTERY_CAPACITY_KWH
        )

        available_capacity_kwh = max(
            available_capacity_kwh,
            0,
        )

        interval_hours = (
            UPDATE_INTERVAL_SECONDS
            / 3600
        )

        if interval_hours <= 0:

            return 0.0

        maximum_input_power = (
            available_capacity_kwh
            / BATTERY_CHARGE_EFFICIENCY
            / interval_hours
        )

        return max(
            0.0,
            min(
                MAX_BATTERY_CHARGE_KW,
                maximum_input_power,
            ),
        )

    def apply_battery_power(
        self,
        requested_power_kw: float,
    ) -> float:
        """
        Apply AI battery command.

        Sign convention:

            + power = discharge battery
            - power = charge battery

        Returns:
            Actual battery power applied.
        """

        interval_hours = (
            UPDATE_INTERVAL_SECONDS
            / 3600
        )

        actual_power_kw = 0.0

        # --------------------------------------------------
        # DISCHARGE
        # --------------------------------------------------

        if requested_power_kw > 0:

            safe_discharge_limit = (
                self.calculate_max_available_discharge_kw()
            )

            actual_power_kw = min(
                requested_power_kw,
                safe_discharge_limit,
            )

            energy_removed_kwh = (
                actual_power_kw
                * interval_hours
                / BATTERY_DISCHARGE_EFFICIENCY
            )

            soc_decrease = (
                energy_removed_kwh
                / BATTERY_CAPACITY_KWH
                * 100
            )

            self.battery_soc -= (
                soc_decrease
            )

        # --------------------------------------------------
        # CHARGE
        # --------------------------------------------------

        elif requested_power_kw < 0:

            requested_charge_kw = abs(
                requested_power_kw
            )

            safe_charge_limit = (
                self.calculate_max_available_charge_kw()
            )

            actual_charge_kw = min(
                requested_charge_kw,
                safe_charge_limit,
            )

            stored_energy_kwh = (
                actual_charge_kw
                * interval_hours
                * BATTERY_CHARGE_EFFICIENCY
            )

            soc_increase = (
                stored_energy_kwh
                / BATTERY_CAPACITY_KWH
                * 100
            )

            self.battery_soc += (
                soc_increase
            )

            actual_power_kw = (
                -actual_charge_kw
            )

        # --------------------------------------------------
        # HOLD
        # --------------------------------------------------

        else:

            self.apply_self_discharge()

            actual_power_kw = 0.0

        self.battery_soc = self.clamp(
            self.battery_soc,
            MIN_BATTERY_SOC,
            MAX_BATTERY_SOC,
        )

        return round(
            actual_power_kw,
            4,
        )

    def apply_self_discharge(
        self,
    ) -> None:

        interval_hours = (
            UPDATE_INTERVAL_SECONDS
            / 3600
        )

        soc_loss = (
            BATTERY_SELF_DISCHARGE_PERCENT_PER_HOUR
            * interval_hours
        )

        self.battery_soc -= (
            soc_loss
        )

    # ======================================================
    # LOAD CONTROL
    # ======================================================

    def apply_load_control(
        self,
        demand_kw: float,
        command: Optional[
            ControlCommand
        ],
    ) -> tuple[
        float,
        float,
    ]:
        """
        Apply demand-response / load-shedding commands.

        Returns:
            adjusted demand
            load reduction
        """

        if command is None:

            return (
                demand_kw,
                0.0,
            )

        action = (
            command.action.upper()
        )

        reduction_percent = 0.0

        if (
            action
            == "PREPARE_LOAD_REDUCTION"
        ):

            reduction_percent = (
                PREPARE_LOAD_REDUCTION_PERCENT
            )

        elif (
            action
            == "SHED_NON_CRITICAL_LOAD"
        ):

            reduction_percent = (
                EMERGENCY_LOAD_SHEDDING_PERCENT
            )

        reduction_kw = (
            demand_kw
            * reduction_percent
            / 100
        )

        adjusted_demand = (
            demand_kw
            - reduction_kw
        )

        adjusted_demand = max(
            adjusted_demand,
            0,
        )

        return (
            round(
                adjusted_demand,
                2,
            ),
            round(
                reduction_kw,
                2,
            ),
        )

    # ======================================================
    # CONTROL COMMAND EXECUTION
    # ======================================================

    def apply_control_command(
        self,
        demand_kw: float,
        solar_kw: float,
        command: Optional[
            ControlCommand
        ],
    ) -> tuple[
        float,
        float,
        float,
    ]:
        """
        Execute AI-generated control command.

        Returns:
            adjusted building demand
            actual battery power
            actual grid import
        """

        # --------------------------------------------------
        # No new command
        # --------------------------------------------------

        if command is None:

            self.last_control_action = (
                "NO_NEW_COMMAND"
            )

            self.last_control_mode = (
                "HOLD"
            )

            self.last_load_reduction_kw = (
                0.0
            )

            actual_battery_power = (
                self.apply_battery_power(
                    0.0
                )
            )

            grid_import_kw = max(
                demand_kw
                - solar_kw,
                0,
            )

            self.last_battery_power_kw = (
                actual_battery_power
            )

            return (
                demand_kw,
                actual_battery_power,
                round(
                    grid_import_kw,
                    2,
                ),
            )

        # --------------------------------------------------
        # Store command metadata
        # --------------------------------------------------

        self.last_control_action = (
            command.action
        )

        self.last_control_mode = (
            command.control_mode
        )

        # --------------------------------------------------
        # Apply load-control command
        # --------------------------------------------------

        (
            adjusted_demand,
            load_reduction_kw,
        ) = self.apply_load_control(
            demand_kw,
            command,
        )

        self.last_load_reduction_kw = (
            load_reduction_kw
        )

        # --------------------------------------------------
        # Battery command
        # --------------------------------------------------

        requested_battery_power = (
            command.battery_power_kw
        )

        actual_battery_power = (
            self.apply_battery_power(
                requested_battery_power
            )
        )

        self.last_battery_power_kw = (
            actual_battery_power
        )

        # --------------------------------------------------
        # Physical power balance
        #
        # Positive battery power:
        #     battery supplies load
        #
        # Negative battery power:
        #     charging increases required power
        # --------------------------------------------------

        grid_import_kw = max(
            adjusted_demand
            - solar_kw
            - actual_battery_power,
            0,
        )

        return (
            adjusted_demand,
            actual_battery_power,
            round(
                grid_import_kw,
                2,
            ),
        )

    # ======================================================
    # COMPLETE TELEMETRY READING
    # ======================================================

    def generate_reading(
        self,
    ) -> EnergyTelemetry:

        now = datetime.now()

        hour = (
            now.hour
            + now.minute / 60
            + now.second / 3600
        )

        # --------------------------------------------------
        # Environment
        # --------------------------------------------------

        cloud_cover = (
            self.update_cloud_cover()
        )

        temperature = (
            self.generate_temperature(
                hour
            )
        )

        humidity = (
            self.update_humidity(
                temperature
            )
        )

        occupancy = (
            self.generate_occupancy(
                hour
            )
        )

        # --------------------------------------------------
        # Renewable generation
        # --------------------------------------------------

        solar_generation = (
            self.generate_solar_power(
                hour,
                cloud_cover,
            )
        )

        # --------------------------------------------------
        # Raw building load
        # --------------------------------------------------

        raw_demand = (
            self.generate_building_demand(
                temperature,
                occupancy,
            )
        )

        # --------------------------------------------------
        # Get AI command generated from previous telemetry
        # --------------------------------------------------

        command = (
            control_state.consume_latest()
        )

        # --------------------------------------------------
        # Closed-loop control
        # --------------------------------------------------

        (
            controlled_demand,
            actual_battery_power,
            actual_grid_import,
        ) = self.apply_control_command(
            raw_demand,
            solar_generation,
            command,
        )

        # --------------------------------------------------
        # Price and carbon
        # --------------------------------------------------

        grid_price = (
            self.generate_grid_price(
                hour,
                controlled_demand,
            )
        )

        carbon_intensity = (
            self.generate_grid_carbon_intensity(
                hour
            )
        )

        # --------------------------------------------------
        # Reading counter
        # --------------------------------------------------

        self.reading_id += 1

        # --------------------------------------------------
        # Console control information
        # --------------------------------------------------

        if command is not None:

            print(
                "\n🎛️ AI CONTROL APPLIED"
            )

            print(
                f"   Source Reading          : "
                f"#{command.reading_id}"
            )

            print(
                f"   Action                  : "
                f"{command.action}"
            )

            print(
                f"   Control Mode            : "
                f"{command.control_mode}"
            )

            print(
                f"   Requested Battery Power : "
                f"{command.battery_power_kw:.2f} kW"
            )

            print(
                f"   Actual Battery Power    : "
                f"{actual_battery_power:.2f} kW"
            )

            print(
                f"   Load Reduction          : "
                f"{self.last_load_reduction_kw:.2f} kW"
            )

            print(
                f"   Resulting Grid Import   : "
                f"{actual_grid_import:.2f} kW"
            )

        return EnergyTelemetry(

            timestamp=now.isoformat(
                timespec="seconds"
            ),

            reading_id=(
                self.reading_id
            ),

            demand_kw=(
                round(
                    controlled_demand,
                    2,
                )
            ),

            solar_generation_kw=(
                solar_generation
            ),

            battery_soc_percent=(
                round(
                    self.battery_soc,
                    4,
                )
            ),

            grid_price_inr_per_kwh=(
                grid_price
            ),

            grid_carbon_intensity_g_per_kwh=(
                carbon_intensity
            ),

            temperature_c=(
                temperature
            ),

            humidity_percent=(
                humidity
            ),

            occupancy_percent=(
                occupancy
            ),

            cloud_cover_percent=(
                cloud_cover
            ),

            net_grid_demand_kw=(
                actual_grid_import
            ),
        )


