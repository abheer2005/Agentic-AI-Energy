class EnergyMQTTInterface:
    """
    Handles both sides of simulator MQTT communication.

    Publishes:
        energy telemetry

    Subscribes:
        AI control commands
    """

    def __init__(
        self,
    ) -> None:

        self.client = mqtt.Client(
            mqtt.CallbackAPIVersion.VERSION2,
            client_id=CLIENT_ID,
        )

        self.connected = False

        self.client.on_connect = (
            self.on_connect
        )

        self.client.on_message = (
            self.on_message
        )

        self.client.on_disconnect = (
            self.on_disconnect
        )

    # ======================================================
    # CONNECT CALLBACK
    # ======================================================

    def on_connect(
        self,
        client,
        userdata,
        flags,
        reason_code,
        properties,
    ) -> None:

        if reason_code == 0:

            self.connected = True

            print(
                f"✅ MQTT connected: "
                f"{BROKER_HOST}:{BROKER_PORT}"
            )

            client.subscribe(
                CONTROL_TOPIC,
                qos=1,
            )

            print(
                f"🎛️ Subscribed to AI control: "
                f"{CONTROL_TOPIC}"
            )

        else:

            self.connected = False

            print(
                f"❌ MQTT connection failed: "
                f"{reason_code}"
            )

    # ======================================================
    # CONTROL MESSAGE CALLBACK
    # ======================================================

    def on_message(
        self,
        client,
        userdata,
        message,
    ) -> None:

        if (
            message.topic
            != CONTROL_TOPIC
        ):

            return

        try:

            payload = (
                message.payload.decode(
                    "utf-8"
                )
            )

            raw_data = json.loads(
                payload
            )

            command = ControlCommand(

                timestamp=str(
                    raw_data[
                        "timestamp"
                    ]
                ),

                reading_id=int(
                    raw_data[
                        "reading_id"
                    ]
                ),

                action=str(
                    raw_data[
                        "action"
                    ]
                ),

                control_mode=str(
                    raw_data[
                        "control_mode"
                    ]
                ),

                battery_power_kw=float(
                    raw_data[
                        "battery_power_kw"
                    ]
                ),

                recommended_grid_import_kw=float(
                    raw_data[
                        "recommended_grid_import_kw"
                    ]
                ),
            )

            control_state.update(
                command
            )

            print(
                "\n📥 CONTROL COMMAND RECEIVED"
            )

            print(
                f"   Reading #{command.reading_id}"
            )

            print(
                f"   Action       : "
                f"{command.action}"
            )

            print(
                f"   Control Mode : "
                f"{command.control_mode}"
            )

            print(
                f"   Battery      : "
                f"{command.battery_power_kw:.2f} kW"
            )

        except (
            KeyError,
            ValueError,
            TypeError,
            json.JSONDecodeError,
        ) as exc:

            print(
                f"❌ Invalid control command: "
                f"{exc}"
            )

    # ======================================================
    # DISCONNECT CALLBACK
    # ======================================================

    def on_disconnect(
        self,
        client,
        userdata,
        disconnect_flags,
        reason_code,
        properties,
    ) -> None:

        self.connected = False

        print(
            f"🔌 MQTT disconnected: "
            f"{reason_code}"
        )

    # ======================================================
    # CONNECT
    # ======================================================

    def connect(
        self,
    ) -> None:

        try:

            self.client.connect(
                BROKER_HOST,
                BROKER_PORT,
                keepalive=60,
            )

            self.client.loop_start()

        except Exception as exc:

            self.connected = False

            print(
                f"❌ MQTT connection failed: "
                f"{exc}"
            )

    # ======================================================
    # TELEMETRY PUBLISH
    # ======================================================

    def publish(
        self,
        telemetry: EnergyTelemetry,
    ) -> None:

        if not self.connected:

            return

        payload = json.dumps(
            asdict(
                telemetry
            )
        )

        result = self.client.publish(
            topic=TELEMETRY_TOPIC,
            payload=payload,
            qos=1,
        )

        if (
            result.rc
            == mqtt.MQTT_ERR_SUCCESS
        ):

            print(
                f"📤 Published → "
                f"{TELEMETRY_TOPIC}"
            )

        else:

            print(
                f"⚠ MQTT publish failed. "
                f"Code: {result.rc}"
            )

    # ======================================================
    # DISCONNECT
    # ======================================================

    def disconnect(
        self,
    ) -> None:

        if self.connected:

            self.client.loop_stop()

            self.client.disconnect()

            self.connected = False

            print(
                "🔌 MQTT disconnected safely."
            )


